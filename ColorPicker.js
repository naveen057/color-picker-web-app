function colorOne() {
    let colorPick = document.getElementById("button1");
    let colorValue = colorPick.textContent;
    let para = document.getElementById('span1');
    para.textContent = colorValue;
    para.style.color = "#49a6e9";
    let div = document.getElementById('d1');
    div.style.backgroundColor = colorValue;
    console.log(colorValue);
}

